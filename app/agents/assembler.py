import pymupdf

from app import db

MARGIN = 46
TEXT_X = 76
TEXT_WIDTH = 612 - MARGIN - TEXT_X
BOTTOM = 735

INK = (0.11, 0.10, 0.09)
MUTED = (0.35, 0.32, 0.28)
GREEN = (0.12, 0.36, 0.25)
RULE = (0.78, 0.74, 0.66)


def _safe(text: str) -> str:
    """The built-in PDF fonts only cover Latin-1, so map or replace anything else."""
    replacements = {"\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"', "\u2013": "-", "\u2014": "-"}
    for old, new in replacements.items():
        text = text.replace(old, new)
    return text.encode("latin-1", "replace").decode("latin-1")


def _wrap(text: str, fontname: str, size: float, width: float) -> list[str]:
    lines: list[str] = []
    line = ""
    for word in _safe(text).split():
        candidate = f"{line} {word}".strip()
        if line and pymupdf.get_text_length(candidate, fontname=fontname, fontsize=size) > width:
            lines.append(line)
            line = word
        else:
            line = candidate
    lines.append(line)
    return lines


def describe_answer(field: dict) -> tuple[str, str]:
    """Return the answer text and where it came from, in plain words."""
    value = (field["value"] or "").strip()
    if not value:
        return "Not answered", "Still needs an answer"
    evidence = db.loads(field["evidence_json"], {}) or {}
    origin = field["origin"]
    if origin == "helper":
        return value, "Your helper, approved by you"
    if origin == "user":
        return value, "You"
    source = f"Your vault: {evidence.get('title', 'a saved document')}, page {evidence.get('page', 1)}"
    if evidence.get("read_from_image"):
        source += " (read from a scan, please check)"
    elif not evidence.get("verified"):
        source += " (not found in the document text, please check)"
    if field["status"] == "proposed":
        source += " - not yet reviewed"
    return value, source


def _fill_form(document, fields: list[dict]):
    values = {
        field["pdf_field"]: field["value"]
        for field in fields
        if field["pdf_field"] and (field["value"] or "").strip()
    }
    for page in document:
        for widget in page.widgets() or []:
            if widget.field_name in values:
                widget.field_value = values[widget.field_name]
                widget.update()


def _new_page(document, title: str):
    page = document.new_page(width=612, height=792)
    page.insert_text((MARGIN, 40), _safe(title).upper(), fontsize=8.5, fontname="hebo", color=MUTED)
    page.draw_line((MARGIN, 52), (612 - MARGIN, 52), color=RULE, width=0.7)
    page.insert_text(
        (MARGIN, 760),
        "Generated by Relay. Answers marked 'not yet reviewed' still need the person's check.",
        fontsize=8,
        color=MUTED,
    )
    return page, 82


def _append_answers(document, task_title: str, fields: list[dict]):
    heading = f"{task_title} - questions and answers"
    page, y = _new_page(document, heading)
    page.insert_text((MARGIN, y), "Questions and answers", fontsize=20, fontname="tiro", color=INK)
    y += 22
    answered = sum(1 for field in fields if (field["value"] or "").strip())
    page.insert_text(
        (MARGIN, y),
        f"{answered} of {len(fields)} questions have an answer.",
        fontsize=10,
        color=MUTED,
    )
    y += 30
    section = None
    for field in fields:
        answer, source = describe_answer(field)
        label_lines = _wrap(field["label"], "hebo", 9.5, TEXT_WIDTH)
        answer_lines = _wrap(answer, "helv", 11.5, TEXT_WIDTH)
        source_lines = _wrap(source, "helv", 8.5, TEXT_WIDTH)
        block = 14 * len(label_lines) + 15 * len(answer_lines) + 11 * len(source_lines) + 16
        header = 26 if field["section"] != section else 0
        if y + header + block > BOTTOM:
            page, y = _new_page(document, heading)
        if header:
            page.insert_text((MARGIN, y + 8), _safe(field["section"]), fontsize=11.5, fontname="tiro", color=GREEN)
            y += header
            section = field["section"]
        page.insert_text((MARGIN, y + 9), f"{field['ord']}.", fontsize=9.5, fontname="hebo", color=MUTED)
        for line in label_lines:
            page.insert_text((TEXT_X, y + 9), line, fontsize=9.5, fontname="hebo", color=MUTED)
            y += 14
        for line in answer_lines:
            colour = INK if (field["value"] or "").strip() else MUTED
            page.insert_text((TEXT_X, y + 10), line, fontsize=11.5, color=colour)
            y += 15
        for line in source_lines:
            page.insert_text((TEXT_X, y + 8), line, fontsize=8.5, color=MUTED)
            y += 11
        y += 8
        page.draw_line((MARGIN, y), (612 - MARGIN, y), color=RULE, width=0.5)
        y += 8


def build_export(session_id: str) -> bytes:
    form = db.row(
        "SELECT path FROM documents WHERE session_id = ? AND role = 'form'",
        (session_id,),
    )
    session = db.row("SELECT task_json FROM sessions WHERE id = ?", (session_id,))
    fields = db.rows(
        """
        SELECT ord, section, label, pdf_field, value, origin, status, evidence_json
        FROM fields WHERE session_id = ? ORDER BY ord
        """,
        (session_id,),
    )
    task = db.loads(session["task_json"], {}) if session else {}
    with pymupdf.open(form["path"]) as document:
        _fill_form(document, fields)
        _append_answers(document, task.get("task") or "Form", fields)
        return document.tobytes(garbage=3, deflate=True)
